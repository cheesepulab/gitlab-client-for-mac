#!/bin/bash
# Builds dist/GitLab Client.app (universal: Apple silicon and Intel).
# Usage: scripts/build.sh            (version from scripts/config.sh)
#        VERSION=0.2.0 scripts/build.sh
set -euo pipefail

cd "$(dirname "$0")/.."
source scripts/config.sh
[ -f scripts/config.local.sh ] && source scripts/config.local.sh

APP="dist/${APP_NAME}.app"
ARCHS=(--arch arm64 --arch x86_64)
# Record source paths relative to the project, so the binaries don't carry this machine's folders.
SWIFT_FLAGS=(-Xswiftc -file-prefix-map -Xswiftc "$PWD=.")

# Defaults for runs without the packaged Info.plist (for example `swift run` or Xcode), kept in
# step with this config. Rewritten only when something changed, so builds stay incremental.
DEFAULTS="Sources/GitLabClient/App/BuildDefaults.swift"
GENERATED="$(mktemp)"
cat > "$GENERATED" <<EOF
// Generated by scripts/build.sh from scripts/config.sh. Edit config.sh, not this file.
// Used when the app runs without its packaged Info.plist, for example from Xcode.
enum BuildDefaults {
    static let bundleID = "${BUNDLE_ID}"
    static let keychainService = "${KEYCHAIN_SERVICE}"
    static let repositoryURL = "${REPO_URL}"
}
EOF
if cmp -s "$GENERATED" "$DEFAULTS"; then rm -f "$GENERATED"; else mv "$GENERATED" "$DEFAULTS"; echo "==> Updated $DEFAULTS"; fi

echo "==> Building ${APP_NAME} ${VERSION} (${BUILD_NUMBER})"
swift build -c release --product "$EXECUTABLE" "${ARCHS[@]}" "${SWIFT_FLAGS[@]}"
BIN_DIR="$(swift build -c release --product "$EXECUTABLE" "${ARCHS[@]}" "${SWIFT_FLAGS[@]}" --show-bin-path)"

echo "==> Assembling ${APP}"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN_DIR/$EXECUTABLE" "$APP/Contents/MacOS/$EXECUTABLE"
# Release binaries ship without debug symbols, which also hold build folder paths.
xcrun strip -S -x "$APP/Contents/MacOS/$EXECUTABLE"
printf 'APPL????' > "$APP/Contents/PkgInfo"

sed -e "s|@APP_NAME@|${APP_NAME}|g" \
    -e "s|@EXECUTABLE@|${EXECUTABLE}|g" \
    -e "s|@BUNDLE_ID@|${BUNDLE_ID}|g" \
    -e "s|@KEYCHAIN_SERVICE@|${KEYCHAIN_SERVICE}|g" \
    -e "s|@VERSION@|${VERSION}|g" \
    -e "s|@BUILD_NUMBER@|${BUILD_NUMBER}|g" \
    -e "s|@YEAR@|$(date +%Y)|g" \
    -e "s|@COPYRIGHT_NAME@|${COPYRIGHT_NAME}|g" \
    -e "s|@REPO_URL@|${REPO_URL}|g" \
    Resources/Info.plist > "$APP/Contents/Info.plist"
plutil -lint "$APP/Contents/Info.plist" >/dev/null

echo "==> Drawing app icon"
swift scripts/make-icon.swift "$APP/Contents/Resources/AppIcon.icns"

# Stop if any file in the app still names this machine's home folder or project folder.
for local_path in "$HOME" "$PWD"; do
    if grep -r -a -q -F "$local_path" "$APP"; then
        rm -rf "$APP"
        echo "error: the app contains a local path ($local_path). Build removed." >&2
        exit 1
    fi
done

IDENTITY="${SIGN_IDENTITY:--}"
case "$IDENTITY" in
    *Distribution*)
        echo "error: refusing to sign with a Distribution certificate ($IDENTITY)." >&2
        echo "       Use your Personal Team 'Apple Development' certificate, or leave SIGN_IDENTITY empty." >&2
        exit 1 ;;
esac
if [ "$IDENTITY" = "-" ]; then
    echo "==> Signing ad-hoc"
elif [ -z "${SIGN_TEAM_ID:-}" ]; then
    # The code in brackets in a certificate's name is not its team, so the team must be stated.
    echo "error: SIGN_IDENTITY is set but SIGN_TEAM_ID is not. Run scripts/signing-identities.sh," >&2
    echo "       then set SIGN_TEAM_ID in scripts/config.local.sh to your Personal Team's ID." >&2
    exit 1
else
    echo "==> Signing with: $IDENTITY (expecting team $SIGN_TEAM_ID)"
fi
# Hardened Runtime on, App Sandbox off: the app needs ~/.ssh, the ssh-agent socket and the
# user's own git and AI command-line tools.
codesign --force --options runtime --timestamp=none --sign "$IDENTITY" "$APP"
codesign --verify --deep --strict "$APP"

if [ "$IDENTITY" != "-" ]; then
    # Check the team codesign actually recorded, so a company certificate can't slip into a release.
    SIGNED_TEAM="$(codesign -dv "$APP" 2>&1 | sed -n 's/^TeamIdentifier=//p')"
    if [ "$SIGNED_TEAM" != "$SIGN_TEAM_ID" ]; then
        rm -rf "$APP"
        echo "error: the app was signed for team '$SIGNED_TEAM', not '$SIGN_TEAM_ID'. Build removed." >&2
        exit 1
    fi
    echo "==> Signed for team $SIGNED_TEAM"
fi

echo "==> Built $APP"
